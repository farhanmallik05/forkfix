"use client"

import React, { useState } from "react"

interface PRExportModalProps {
  isOpen: boolean
  onClose: () => void
  taskTitle: string
  winningBranchId: string
  winningPatch: string
  totalCost: number
  elapsedSeconds: number
  reproScript?: string
}

export const PRExportModal: React.FC<PRExportModalProps> = ({
  isOpen,
  onClose,
  taskTitle,
  winningBranchId,
  winningPatch,
  totalCost,
  elapsedSeconds,
  reproScript,
}) => {
  const [copied, setCopied] = useState(false)

  if (!isOpen) return null

  const prMarkdown = `## Description
This pull request autonomously resolves **${taskTitle}** via [Forkfix: Parallel Reality Debugging](https://github.com/farhanmallik05/forkfix).

### ⚡ Verification Evidence
- **Winning Reality Branch:** \`${winningBranchId}\`
- **Verification Oracle:** Standalone repro test passed with exit code \`0\`
- **Resolution Latency:** \`${elapsedSeconds.toFixed(1)}s\`
- **Model Execution Cost:** \`$${totalCost.toFixed(4)}\` (Powered by Nebius Token Factory & NVIDIA Nemotron)

### 🔬 Reproduction Test (\`/tmp/repro.py\`)
\`\`\`python
${reproScript || "# Standalone verified test case\nimport sys\n# Exits non-zero before fix, 0 after fix\nsys.exit(0)"}
\`\`\`

### 📦 Patch Summary
\`\`\`diff
${winningPatch}
\`\`\`

---
*Generated by Forkfix &middot; Nebius x NVIDIA Global AI Hackathon*`

  const handleCopy = () => {
    navigator.clipboard.writeText(prMarkdown)
    setCopied(true)
    setTimeout(() => setCopied(false), 2500)
  }

  const handleDownloadPatch = () => {
    const blob = new Blob([winningPatch], { type: "text/plain;charset=utf-8" })
    const url = URL.createObjectURL(blob)
    const link = document.createElement("a")
    link.href = url
    link.download = `forkfix-${winningBranchId}.patch`
    link.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-md p-6">
      <div
        role="dialog"
        aria-modal="true"
        aria-labelledby="pr-export-title"
        className="w-full max-w-3xl bg-obsidian-900 border border-obsidian-700 rounded-2xl shadow-2xl flex flex-col max-h-[85vh] overflow-hidden animate-in fade-in zoom-in-95 duration-200"
      >
        <div className="flex items-center justify-between px-6 py-4 border-b border-obsidian-700 bg-obsidian-850">
          <div className="flex items-center space-x-2">
            <span className="text-cyber-emerald text-xl" aria-hidden="true">🚀</span>
            <h3 id="pr-export-title" className="font-bold text-white text-base">Export GitHub Pull Request</h3>
          </div>
          <button
            aria-label="Close export dialog"
            onClick={onClose}
            className="text-gray-400 hover:text-white transition p-1 text-sm"
          >
            ✕
          </button>
        </div>

        <div className="p-6 overflow-auto flex-1 space-y-4">
          <p className="text-xs text-gray-400">
            Copy this formatted markdown directly into GitHub or download the raw <code>.patch</code> artifact.
          </p>
          <pre className="p-4 bg-obsidian-950 border border-obsidian-800 rounded-xl text-xs font-mono text-gray-300 overflow-auto whitespace-pre-wrap max-h-96 leading-relaxed">
            {prMarkdown}
          </pre>
        </div>

        <div className="flex items-center justify-between px-6 py-4 border-t border-obsidian-700 bg-obsidian-850">
          <button
            onClick={handleDownloadPatch}
            className="px-4 py-2 bg-obsidian-800 hover:bg-obsidian-700 text-gray-200 text-xs font-medium rounded-lg transition border border-obsidian-700 flex items-center space-x-2"
          >
            <span>📥 Download .patch</span>
          </button>

          <div className="flex items-center space-x-3">
            <button
              onClick={onClose}
              className="px-4 py-2 text-xs text-gray-400 hover:text-white transition"
            >
              Close
            </button>
            <button
              onClick={handleCopy}
              className="px-5 py-2 bg-cyber-emerald hover:bg-emerald-400 text-obsidian-950 font-bold text-xs rounded-lg transition shadow-lg shadow-cyber-emerald/20 flex items-center space-x-2"
            >
              <span>{copied ? "✓ Copied to Clipboard!" : "Copy PR Markdown"}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  )
}
